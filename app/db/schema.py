from app.db.connection import get_connection


def init_db():
    """Создаёт таблицы PostgreSQL, если они ещё не существуют."""

    with get_connection() as connection:
        with connection.cursor() as cursor:
            # Добавляем новые колонки в таблицу sleep_notifications, если их нет
            cursor.execute("""
                ALTER TABLE sleep_notifications
                ADD COLUMN IF NOT EXISTS telegram_message_id BIGINT
            """)
            cursor.execute("""
                ALTER TABLE sleep_notifications
                ADD COLUMN IF NOT EXISTS last_error TEXT
            """)

            # Ручные записи сна
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS sleep_records (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    sleep_date TEXT NOT NULL,
                    sleep_start TEXT NOT NULL,
                    wake_up TEXT,
                    duration_minutes INTEGER,
                    source TEXT NOT NULL DEFAULT 'manual'
                )
            """)

            # События активности
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS activity_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    event_time TEXT NOT NULL,
                    event_type TEXT NOT NULL,
                    source TEXT NOT NULL DEFAULT 'telegram',
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE(user_id, event_time, event_type, source)
                )
            """)

            # Автоматически обнаруженные периоды сна
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS detected_sleep (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    sleep_start TEXT NOT NULL,
                    sleep_end TEXT NOT NULL,
                    total_minutes INTEGER NOT NULL,
                    sleep_minutes INTEGER NOT NULL,
                    activity_minutes INTEGER NOT NULL,
                    source TEXT NOT NULL DEFAULT 'activity_analysis',
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE(user_id, sleep_start, sleep_end)
                )
            """)

            # Уведомления о сне
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS sleep_notifications (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    detected_sleep_id BIGINT NOT NULL UNIQUE,
                    status TEXT NOT NULL DEFAULT 'pending'
                        CHECK(status IN (
                            'pending',
                            'sending',
                            'sent',
                            'confirmed',
                            'failed'
                        )),
                    telegram_message_id BIGINT,
                    sent_at TEXT,
                    last_error TEXT,
                    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (detected_sleep_id)
                        REFERENCES detected_sleep(id)
                )
            """)

            # Индекс для быстрого поиска активности
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_activity_user_time
                ON activity_events(user_id, event_time)
            """)